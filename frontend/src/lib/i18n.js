const dictionaries = {
  EN: en,
  FR: { ...en, ...fr },
  ES: { ...en, ...es },
  DE: { ...en, ...de },
  IT: { ...en, ...it },
  PT: { ...en, ...pt },
  AR: { ...en, ...ar },
};

let currentLang = (typeof localStorage !== 'undefined' && localStorage.getItem('nb_lang')) || 'EN';

export function setLang(code) {
  currentLang = code;
  if (typeof localStorage !== 'undefined') localStorage.setItem('nb_lang', code);
  if (typeof document !== 'undefined') {
    document.documentElement.dir = LANGS.find((l) => l.code === code)?.dir || 'ltr';
    document.documentElement.lang = code.toLowerCase();
  }
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('nb-lang-change', { detail: code }));
  }
}

export function getLang() {
  return currentLang;
}

export function t(key) {
  const dict = dictionaries[currentLang] || en;
  return dict[key] ?? en[key] ?? key;
}

export function tLang(lang, key) {
  const dict = dictionaries[lang] || en;
  return dict[key] ?? en[key] ?? key;
}

export function interpolate(template, vars) {
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

export function interpolateLang(lang, template, vars) {
  return tLang(lang, template).replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

if (typeof window !== 'undefined') setLang(currentLang);
